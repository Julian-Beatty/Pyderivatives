@register_transform("ross_recovery")
@register_transform("ross")
class RossRecoveryKernel(MeasureTransform):
    """
    Audrino-Huitema-Ludwig style regularized Ross recovery.

    Main implementation choices
    ---------------------------
    1. The transition state-price matrix is estimated from maturity pairs
       separated by ``transition_step_days`` rather than from adjacent tenors.

    2. For each ridge penalty, the transition matrix is estimated by
       nonnegative Tikhonov-regularized least squares:

           min_{p_j >= 0} ||A p_j - b_j||_2^2 + zeta ||p_j||_2^2.

    3. The ridge penalty is selected by generalized KL discrepancy between
       observed state prices and the state prices generated by unrolling the
       estimated transition matrix.

    4. The right Perron eigenvector z is recovered on the coarse state grid.
       The pricing kernel is proportional to 1/z.

    5. The recovered Perron vector z is interpolated back to the original
       fine state grid using PCHIP. This shape-preserving interpolator avoids
       the negative overshoot that can occur with ordinary cubic splines.
       Physical probability masses at
       each observed maturity are then obtained directly as

           recovered_mass_j(x) proportional to z(x) * state_price_mass_j(x).

       The same state-dependent pricing kernel is therefore used at every
       maturity for a given valuation date.

    Notes
    -----
    A faithful quarterly implementation requires a sufficiently long and
    densely sampled maturity surface. With daily tenors from about 20 to 730
    days and ``transition_step_days=90``, there are roughly 621 maturity-pair
    equations for a 150-state transition matrix.

    One-day transitions are also supported. For a grid containing 5, 6, ...,
    34 days, ``transition_step_days=1`` uses the 29 adjacent maturity pairs.
    Such a system is underdetermined when the recovery grid has more than 29
    states; this is allowed because ridge regularization supplies a solution,
    but the condition, rank, fit, sparsity, and spectral diagnostics will flag
    the identification weakness.
    """

    def __init__(
        self,
        *,
        recovery_grid_size: Optional[int] = 150,
        recovery_grid_bounds: Optional[Tuple[float, float]] = None,
        transition_step_days: int = 90,
        maturity_pair_tolerance_days: float = 0.51,
        min_transition_pairs: Optional[int] = None,
        zeta_grid: Optional[np.ndarray] = None,
        state_price_floor: float = 1e-20,
        current_state: float = 0.0,
        nnls_max_iter: int = 500,
        eigenvector_negative_tolerance: float = 1e-10,
        eigenpair_residual_tolerance: float = 1e-7,
        key_spec: KeySpec = KeySpec(),
        eps: float = 1e-10,
        verbose: bool = True,
        penalty_value: float = 1e100,
        cache_spec: CacheSpec = CacheSpec(),
        behavioral: bool = False,
        stock_df=None,
        stock_date_col: str = "date",
        volume_col: str = "volume",
        k1: float = 1.0,
        k2: float = 1.2,
        k3: float = 1.0,
        sentiment_alpha: float = 0.05,
        **kwargs,
    ):
        super().__init__(
            key_spec=key_spec,
            min_obs=1,
            eps=eps,
            verbose=verbose,
            penalty_value=penalty_value,
            cache_spec=cache_spec,
            behavioral=behavioral,
            stock_df=stock_df,
            stock_date_col=stock_date_col,
            volume_col=volume_col,
            k1=k1,
            k2=k2,
            k3=k3,
            sentiment_alpha=sentiment_alpha,
        )

        if recovery_grid_size is None:
            self.recovery_grid_size = None
        else:
            recovery_grid_size = int(recovery_grid_size)
            if recovery_grid_size < 10:
                raise ValueError(
                    "recovery_grid_size must be at least 10 or None."
                )
            self.recovery_grid_size = recovery_grid_size

        if recovery_grid_bounds is None:
            self.recovery_grid_bounds = None
        else:
            if len(recovery_grid_bounds) != 2:
                raise ValueError(
                    "recovery_grid_bounds must contain (lower, upper)."
                )
            lower, upper = map(float, recovery_grid_bounds)
            if (
                not np.isfinite(lower)
                or not np.isfinite(upper)
                or lower >= upper
            ):
                raise ValueError(
                    "recovery_grid_bounds must be finite and increasing."
                )
            self.recovery_grid_bounds = (lower, upper)

        self.transition_step_days = int(transition_step_days)
        if self.transition_step_days < 1:
            raise ValueError("transition_step_days must be at least 1.")

        self.maturity_pair_tolerance_days = float(
            maturity_pair_tolerance_days
        )
        if (
            not np.isfinite(self.maturity_pair_tolerance_days)
            or self.maturity_pair_tolerance_days < 0
        ):
            raise ValueError(
                "maturity_pair_tolerance_days must be finite and nonnegative."
            )

        self.min_transition_pairs = (
            None
            if min_transition_pairs is None
            else int(min_transition_pairs)
        )
        if (
            self.min_transition_pairs is not None
            and self.min_transition_pairs < 2
        ):
            raise ValueError("min_transition_pairs must be at least 2.")

        self.zeta_grid = (
            np.asarray(zeta_grid, dtype=float).ravel()
            if zeta_grid is not None
            else np.linspace(0.0, 0.2, 41)
        )
        if self.zeta_grid.size == 0:
            raise ValueError("zeta_grid cannot be empty.")
        if (
            np.any(~np.isfinite(self.zeta_grid))
            or np.any(self.zeta_grid < 0)
        ):
            raise ValueError(
                "zeta_grid must contain finite nonnegative values."
            )

        self.state_price_floor = float(state_price_floor)
        if self.state_price_floor <= 0:
            raise ValueError("state_price_floor must be positive.")

        self.current_state = float(current_state)
        self.nnls_max_iter = int(nnls_max_iter)
        if self.nnls_max_iter < 1:
            raise ValueError("nnls_max_iter must be at least 1.")

        self.eigenvector_negative_tolerance = float(
            eigenvector_negative_tolerance
        )
        self.eigenpair_residual_tolerance = float(
            eigenpair_residual_tolerance
        )

        self.is_fitted_ = True

    def fit(self, *args, **kwargs):
        self.is_fitted_ = True
        return self

    def _cache_params(self) -> dict:
        return {
            "recovery_grid_size": self.recovery_grid_size,
            "recovery_grid_bounds": self.recovery_grid_bounds,
            "transition_step_days": self.transition_step_days,
            "maturity_pair_tolerance_days":
                self.maturity_pair_tolerance_days,
            "min_transition_pairs": self.min_transition_pairs,
            "zeta_grid": self.zeta_grid,
            "state_price_floor": self.state_price_floor,
            "current_state": self.current_state,
            "nnls_max_iter": self.nnls_max_iter,
            "eigenvector_negative_tolerance":
                self.eigenvector_negative_tolerance,
            "eigenpair_residual_tolerance":
                self.eigenpair_residual_tolerance,
        }

    def transform_info(
        self,
        info: dict,
        *,
        bootstrap: bool = False,
        bootstrap_spec: BootstrapSpec = BootstrapSpec(),
    ) -> dict:
        return self.transform_rnd(
            info,
            bootstrap=bootstrap,
            bootstrap_spec=bootstrap_spec,
        )

    def transform_rnd(
        self,
        info: dict,
        *,
        bootstrap: bool = False,
        bootstrap_spec: BootstrapSpec = BootstrapSpec(),
    ) -> dict:
        original_x, original_rnd, original_cdf, T_grid = (
            self._extract_surfaces(info)
        )
        original_x = _as_1d(original_x)
        T_grid = _as_1d(T_grid)

        self._validate_surface(
            x_grid=original_x,
            surface=original_rnd,
            T_grid=T_grid,
        )

        S0 = _find_spot(info, self.key_spec.spot_keys)

        rnd_lr_surface = np.vstack([
            _trapz_normalize_density(
                original_x,
                original_rnd[j],
                eps=self.eps,
            )
            for j in range(T_grid.size)
        ])
        if np.any(~np.isfinite(rnd_lr_surface)):
            raise ValueError(
                "At least one original risk-neutral density is invalid."
            )

        cdf_lr_surface = self._clean_or_rebuild_cdf_surface(
            x_grid=original_x,
            rnd_lr_surface=rnd_lr_surface,
            supplied_cdf=original_cdf,
        )

        # Estimate the transition matrix and Perron vector on a coarse grid.
        recovery_x = self._build_recovery_grid(original_x)
        recovery_rnd = self._interpolate_density_surface(
            source_x=original_x,
            target_x=recovery_x,
            surface=rnd_lr_surface,
        )

        recovery = self._estimate_recovery_from_surface(
            x_grid=recovery_x,
            rnd_lr_surface=recovery_rnd,
            T_grid=T_grid,
            info=info,
            original_grid_size=original_x.size,
        )

        # Interpolate the right Perron vector, not the recovered density.
        z_full = self._interpolate_eigenfunction(
            source_x=recovery_x,
            target_x=original_x,
            z=recovery.eigenfunction,
        )

        # Normalize z at the current state. Its scale is otherwise arbitrary.
        i0_full = int(
            np.argmin(np.abs(original_x - self.current_state))
        )
        z_at_current = float(z_full[i0_full])
        if not np.isfinite(z_at_current) or z_at_current <= self.eps:
            raise ValueError(
                "Interpolated Perron vector is invalid at current state."
            )
        z_full = z_full / z_at_current

        kernel_full = 1.0 / np.maximum(z_full, self.eps)
        kernel_full = kernel_full / kernel_full[i0_full]

        # Keep the user's existing scalar-rate discount treatment.
        state_price_full = self._state_price_matrix(
            original_x,
            rnd_lr_surface,
            T_grid,
            info,
        )

        # Audrino-style cross-sectional recovery:
        # physical mass is proportional to z * observed state-price mass.
        physical_lr_surface = self._physical_surface_from_eigenfunction(
            x_grid=original_x,
            state_price_matrix=state_price_full,
            z=z_full,
        )

        physical_cdf_lr_surface = np.vstack([
            _cdf_from_density(
                original_x,
                physical_lr_surface[j],
                eps=self.eps,
            )
            for j in range(T_grid.size)
        ])

        pricing_kernel_surface = np.tile(
            kernel_full,
            (T_grid.size, 1),
        )

        measure_weight_surface = np.tile(
            z_full,
            (T_grid.size, 1),
        )

        rra_surface = np.vstack([
            self.compute_relative_risk_aversion(
                original_x,
                kernel_full,
            )
            for _ in range(T_grid.size)
        ])

        grid_lr, grid_r, grid_k = build_axis_grids(
            original_x,
            S0,
        )

        rnd_r_surface = lr_surface_to_r_surface(
            rnd_lr_surface,
            grid_r,
        )
        physical_r_surface = lr_surface_to_r_surface(
            physical_lr_surface,
            grid_r,
        )

        rnd_k_surface = lr_surface_to_k_surface(
            rnd_lr_surface,
            grid_k,
        )
        physical_k_surface = lr_surface_to_k_surface(
            physical_lr_surface,
            grid_k,
        )

        physical_moments = physical_moments_table(
            T_grid=T_grid,
            r_grid=grid_lr,
            physical_lr_surface=physical_lr_surface,
        )
        risk_neutral_moments = physical_moments_table(
            T_grid=T_grid,
            r_grid=grid_lr,
            physical_lr_surface=rnd_lr_surface,
        )

        status_by_T = [
            {
                "T": float(T),
                "matched_T": float(T),
                "status": "success",
                "ross_recovery_grid_size": int(recovery_x.size),
                "transition_step_days":
                    int(self.transition_step_days),
            }
            for T in T_grid
        ]

        out = build_transform_output(
            method_name=self.method_name,
            info=info,
            fit_trim_alpha=None,
            T_grid=T_grid,
            matched_T_grid=T_grid,
            status_by_T=status_by_T,
            grid_lr=grid_lr,
            grid_r=grid_r,
            grid_k=grid_k,
            rnd_lr_surface=rnd_lr_surface,
            rnd_r_surface=rnd_r_surface,
            rnd_k_surface=rnd_k_surface,
            cdf_lr_surface=cdf_lr_surface,
            cdf_r_surface=cdf_lr_surface,
            cdf_k_surface=cdf_lr_surface,
            base_physical_lr_surface=physical_lr_surface,
            base_physical_r_surface=physical_r_surface,
            base_physical_k_surface=physical_k_surface,
            base_physical_cdf_lr_surface=physical_cdf_lr_surface,
            base_physical_cdf_r_surface=physical_cdf_lr_surface,
            base_physical_cdf_k_surface=physical_cdf_lr_surface,
            physical_lr_surface=physical_lr_surface,
            physical_r_surface=physical_r_surface,
            physical_k_surface=physical_k_surface,
            physical_cdf_lr_surface=physical_cdf_lr_surface,
            physical_cdf_r_surface=physical_cdf_lr_surface,
            physical_cdf_k_surface=physical_cdf_lr_surface,
            pricing_kernel_surface=pricing_kernel_surface,
            rra_surface=rra_surface,
            measure_weight_surface=measure_weight_surface,
            base_pricing_kernel_surface=pricing_kernel_surface,
            base_measure_weight_surface=measure_weight_surface,
            fit_diagnostics={},
            S0=S0,
            physical_moments=physical_moments,
            risk_neutral_moments=risk_neutral_moments,
            base_physical_moments=physical_moments,
        )

        out["ross_recovery"] = recovery.__dict__
        out["ross_recovery"]["eigenfunction_original_grid"] = (
            z_full.copy()
        )
        out["ross_recovery"][
            "pricing_kernel_original_grid"
        ] = kernel_full.copy()

        out["ross_recovery_diagnostics"] = {
            "transition_system_shape": (
                int(recovery.transition_system_rows),
                int(recovery.transition_system_columns),
            ),
            "transition_system_rank":
                int(recovery.transition_system_rank),
            "transition_system_condition_number":
                float(
                    recovery.transition_system_condition_number
                ),
            "transition_pair_count":
                int(recovery.transition_pair_count),
            "transition_fit_rmse":
                float(recovery.transition_fit_rmse),
            "transition_fit_relative_rmse":
                float(
                    recovery.transition_fit_relative_rmse
                ),
            "unrolled_state_price_rmse":
                float(
                    recovery.selected_kl_reconstruction_rmse
                ),
            "unrolled_state_price_relative_rmse":
                float(
                    recovery
                    .selected_kl_reconstruction_relative_rmse
                ),
            "selected_zeta":
                float(recovery.ridge_zeta),
            "selected_generalized_kl":
                float(recovery.kl_loss),
            "dominant_eigenvalue":
                float(recovery.dominant_eigenvalue),
            "subdominant_eigenvalue_abs":
                float(
                    recovery.subdominant_eigenvalue_abs
                ),
            "subdominant_to_dominant_ratio":
                float(
                    recovery
                    .subdominant_to_dominant_ratio
                ),
            "eigenpair_residual":
                float(recovery.eigenpair_residual),
            "eigenpair_residual_tolerance":
                float(self.eigenpair_residual_tolerance),
            "eigenpair_residual_exceeds_tolerance":
                bool(
                    recovery.eigenpair_residual
                    > self.eigenpair_residual_tolerance
                ),
            "physical_transition_max_row_sum_error":
                float(
                    recovery
                    .recovered_transition_row_sum_error
                ),
            "transition_matrix_zero_fraction":
                float(
                    recovery
                    .transition_matrix_zero_fraction
                ),
            "transition_matrix_row_sum_range": (
                float(
                    recovery
                    .transition_matrix_min_row_sum
                ),
                float(
                    recovery
                    .transition_matrix_max_row_sum
                ),
            ),
            "warnings":
                list(recovery.diagnostic_warnings),
            "zeta_values_tested":
                recovery.zeta_values_tested.copy(),
            "zeta_kl_values":
                recovery.zeta_kl_values.copy(),
        }

        out["ross_recovery_settings"] = {
            "original_grid_size": int(original_x.size),
            "recovery_grid_size": int(recovery_x.size),
            "requested_recovery_grid_size":
                self.recovery_grid_size,
            "recovery_grid_bounds": (
                float(recovery_x[0]),
                float(recovery_x[-1]),
            ),
            "transition_step_days":
                int(self.transition_step_days),
            "maturity_pair_tolerance_days":
                float(self.maturity_pair_tolerance_days),
            "transition_pair_count":
                int(recovery.transition_pair_count),
            "zeta_grid_size": int(self.zeta_grid.size),
            "nnls_max_iter": int(self.nnls_max_iter),
            "eigenpair_residual_tolerance":
                float(self.eigenpair_residual_tolerance),
            "eigenpair_residual_is_fatal": False,
            "interpolated_quantity":
                "right Perron eigenvector",
            "eigenvector_interpolation":
                "PCHIP",
            "physical_recovery":
                "z_times_observed_state_price_mass",
            "common_kernel_across_maturities": True,
        }

        out["bootstrap"] = {
            "enabled": False,
            "requested": bool(bootstrap),
            "message": (
                "Ross recovery bootstrap is not implemented."
                if bootstrap
                else None
            ),
        }

        return out

