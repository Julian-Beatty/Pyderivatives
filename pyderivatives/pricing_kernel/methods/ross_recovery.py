    def _validate_surface(
        self,
        *,
        x_grid,
        surface,
        T_grid,
    ) -> None:
        x = _as_1d(x_grid)
        T = _as_1d(T_grid)
        Z = np.asarray(surface, dtype=float)

        if x.size < 2 or np.any(~np.isfinite(x)):
            raise ValueError(
                "x_grid must contain at least two finite values."
            )
        if np.any(np.diff(x) <= 0):
            raise ValueError("x_grid must be strictly increasing.")

        if T.size < 3:
            raise ValueError(
                "Ross recovery needs at least three maturities."
            )
        if np.any(~np.isfinite(T)) or np.any(np.diff(T) <= 0):
            raise ValueError(
                "T_grid must be finite and strictly increasing."
            )

        if Z.shape != (T.size, x.size):
            raise ValueError(
                "rnd_lr_surface must have shape "
                f"{(T.size, x.size)}, got {Z.shape}."
            )

    def _build_recovery_grid(
        self,
        original_x: np.ndarray,
    ) -> np.ndarray:
        x = _as_1d(original_x)

        if self.recovery_grid_bounds is None:
            lower, upper = float(x[0]), float(x[-1])
        else:
            lower, upper = self.recovery_grid_bounds
            if lower < float(x[0]) or upper > float(x[-1]):
                raise ValueError(
                    "recovery_grid_bounds must lie inside "
                    "the original x grid."
                )

        if not (lower <= self.current_state <= upper):
            raise ValueError(
                "current_state must lie inside recovery_grid_bounds."
            )

        if self.recovery_grid_size is None:
            recovery_x = x[(x >= lower) & (x <= upper)]
            if recovery_x.size < 10:
                raise ValueError(
                    "The selected bounds contain fewer than 10 states."
                )
            return recovery_x.copy()

        n_states = min(
            int(self.recovery_grid_size),
            int(x.size),
        )
        if n_states < 10:
            raise ValueError(
                "The effective recovery grid must have at least 10 states."
            )

        return np.linspace(
            lower,
            upper,
            n_states,
            dtype=float,
        )

    def _interpolate_density_surface(
        self,
        *,
        source_x,
        target_x,
        surface,
    ) -> np.ndarray:
        source_x = _as_1d(source_x)
        target_x = _as_1d(target_x)
        surface = np.asarray(surface, dtype=float)

        if (
            surface.ndim != 2
            or surface.shape[1] != source_x.size
        ):
            raise ValueError(
                "surface must be 2D with one column "
                "for each source_x state."
            )

        rows = []

        for row in surface:
            row = np.where(
                np.isfinite(row) & (row >= 0),
                row,
                0.0,
            )

            interpolated = np.interp(
                target_x,
                source_x,
                row,
                left=0.0,
                right=0.0,
            )

            interpolated = _trapz_normalize_density(
                target_x,
                interpolated,
                eps=self.eps,
            )

            if np.any(~np.isfinite(interpolated)):
                raise ValueError(
                    "A density row could not be normalized "
                    "after interpolation."
                )

            rows.append(interpolated)

        return np.vstack(rows)

    def _interpolate_eigenfunction(
        self,
        *,
        source_x,
        target_x,
        z,
    ) -> np.ndarray:
        """
        Interpolate the positive Perron vector with PCHIP.

        PCHIP is shape preserving and avoids the negative overshoot that can
        occur when a sparse positive eigenvector is interpolated with an
        unconstrained cubic spline.
        """
        source_x = _as_1d(source_x)
        target_x = _as_1d(target_x)
        z = _as_1d(z)

        if source_x.size != z.size:
            raise ValueError(
                "source_x and z must have the same length."
            )
        if source_x.size < 2:
            raise ValueError(
                "PCHIP interpolation needs at least two states."
            )
        if np.any(~np.isfinite(source_x)) or np.any(np.diff(source_x) <= 0):
            raise ValueError(
                "source_x must be finite and strictly increasing."
            )
        if np.any(~np.isfinite(z)) or np.any(z <= 0):
            raise ValueError(
                "The Perron eigenvector must be finite and positive."
            )

        interpolator = PchipInterpolator(
            source_x,
            z,
            extrapolate=False,
        )
        z_full = np.asarray(
            interpolator(target_x),
            dtype=float,
        )

        outside = (
            (target_x < source_x[0])
            | (target_x > source_x[-1])
        )
        z_full[outside] = np.nan

        if np.any(~np.isfinite(z_full)):
            raise ValueError(
                "The recovery grid must cover the complete output grid."
            )

        scale = max(
            float(np.max(np.abs(z))),
            1.0,
        )
        negative_tol = (
            self.eigenvector_negative_tolerance * scale
        )
        min_z_full = float(np.min(z_full))

        if min_z_full < -negative_tol:
            raise ValueError(
                "PCHIP interpolation produced materially negative "
                "Perron-vector values. Check the recovery grid and "
                "eigenvector diagnostics."
            )

        z_full = np.maximum(
            z_full,
            self.eps,
        )
        return z_full

    def _clean_or_rebuild_cdf_surface(
        self,
        *,
        x_grid,
        rnd_lr_surface,
        supplied_cdf,
    ) -> np.ndarray:
        x = _as_1d(x_grid)
        supplied = np.asarray(
            supplied_cdf,
            dtype=float,
        )

        if (
            supplied.shape == rnd_lr_surface.shape
            and np.all(np.isfinite(supplied))
        ):
            cleaned = np.maximum.accumulate(
                np.clip(supplied, 0.0, 1.0),
                axis=1,
            )
            spans = cleaned[:, -1] - cleaned[:, 0]

            if (
                np.all(np.isfinite(spans))
                and np.all(spans > self.eps)
            ):
                cleaned = (
                    cleaned - cleaned[:, [0]]
                ) / spans[:, None]
                cleaned[:, 0] = 0.0
                cleaned[:, -1] = 1.0
                return cleaned

        return np.vstack([
            _cdf_from_density(
                x,
                row,
                eps=self.eps,
            )
            for row in rnd_lr_surface
        ])

    def _state_price_matrix(
        self,
        x_grid,
        rnd_lr_surface,
        T_grid,
        info,
    ) -> np.ndarray:
        """
        Build state-price masses.

        The scalar-rate discount treatment is intentionally retained from
        the previous implementation, as requested.
        """
        r_rate = float(info.get("r", 0.0))
        if not np.isfinite(r_rate):
            r_rate = 0.0

        x = _as_1d(x_grid)
        T_grid = _as_1d(T_grid)
        dx = np.gradient(x)

        columns = []

        for j, T in enumerate(T_grid):
            f_q = _trapz_normalize_density(
                x,
                rnd_lr_surface[j],
                eps=self.eps,
            )
            if np.any(~np.isfinite(f_q)):
                raise ValueError(
                    f"Invalid RND at maturity index {j}."
                )

            discount = np.exp(
                -r_rate * float(T)
            )
            state_prices = (
                discount
                * f_q
                * dx
            )

            columns.append(
                np.maximum(
                    state_prices,
                    self.state_price_floor,
                )
            )

        return np.column_stack(columns)

    def _maturity_pair_indices(
        self,
        T_grid,
    ) -> Tuple[np.ndarray, np.ndarray]:
        T_days = 365.0 * _as_1d(T_grid)
        step = float(self.transition_step_days)
        tol = float(self.maturity_pair_tolerance_days)

        source_indices = []
        target_indices = []

        for i, day in enumerate(T_days):
            target_day = day + step
            j = int(
                np.argmin(
                    np.abs(T_days - target_day)
                )
            )

            if (
                j > i
                and abs(T_days[j] - target_day) <= tol
            ):
                source_indices.append(i)
                target_indices.append(j)

        if not source_indices:
            min_day = float(np.min(T_days))
            max_day = float(np.max(T_days))
            raise ValueError(
                "No maturity pairs are separated by "
                f"{self.transition_step_days} days within tolerance "
                f"{tol:g}. Available maturity range is "
                f"{min_day:.2f} to {max_day:.2f} days."
            )

        source = np.asarray(
            source_indices,
            dtype=int,
        )
        target = np.asarray(
            target_indices,
            dtype=int,
        )

        required = (
            self.min_transition_pairs
            if self.min_transition_pairs is not None
            else 2
        )

        if source.size < required:
            raise ValueError(
                f"Only {source.size} usable maturity pairs were found; "
                f"at least {required} are required."
            )

        return source, target

    def _kl_maturity_indices(
        self,
        T_grid,
    ) -> np.ndarray:
        """
        Select maturities corresponding to one, two, ... transition steps
        beyond the shortest available maturity.

        With a 20-day lower boundary and a 90-day transition, this selects
        approximately 110, 200, 290, 380, ... days.
        """
        T_days = 365.0 * _as_1d(T_grid)
        base_day = float(T_days[0])
        max_day = float(T_days[-1])
        step = float(self.transition_step_days)
        tol = float(self.maturity_pair_tolerance_days)

        indices = []
        k = 1

        while base_day + k * step <= max_day + tol:
            target_day = base_day + k * step
            j = int(
                np.argmin(
                    np.abs(T_days - target_day)
                )
            )

            if abs(T_days[j] - target_day) <= tol:
                indices.append(j)

            k += 1

        if not indices:
            raise ValueError(
                "The maturity surface contains no tenors compatible "
                "with unrolling the selected transition step."
            )

        return np.asarray(
            indices,
            dtype=int,
        )

    def _estimate_recovery_from_surface(
        self,
        *,
        x_grid,
        rnd_lr_surface,
        T_grid,
        info,
        original_grid_size: int,
    ) -> RossRecoveryOutput:
        x = _as_1d(x_grid)
        T_grid = _as_1d(T_grid)

        S = self._state_price_matrix(
            x,
            rnd_lr_surface,
            T_grid,
            info,
        )

        source_idx, target_idx = (
            self._maturity_pair_indices(T_grid)
        )

        A = S[:, source_idx].T
        B = S[:, target_idx].T

        if A.shape[0] < 2:
            raise ValueError(
                "At least two maturity-pair equations are required."
            )

        # Identification and conditioning diagnostics for A.
        transition_rank = int(
            np.linalg.matrix_rank(A)
        )
        singular_values = np.linalg.svd(
            A,
            compute_uv=False,
        )
        if (
            singular_values.size == 0
            or not np.isfinite(singular_values[0])
        ):
            condition_number = np.inf
        elif singular_values[-1] <= np.finfo(float).eps:
            condition_number = np.inf
        else:
            condition_number = float(
                singular_values[0]
                / singular_values[-1]
            )

        i0 = int(
            np.argmin(
                np.abs(x - self.current_state)
            )
        )

        kl_idx = self._kl_maturity_indices(
            T_grid
        )
        S_kl = S[:, kl_idx]

        best = None
        zeta_values = []
        zeta_kl_values = []

        for zeta in self.zeta_grid:
            zeta = float(zeta)

            G = self._solve_transition_nnls(
                A,
                B,
                zeta,
            )

            U = self._markov_state_prices(
                G,
                i0=i0,
                n_steps=kl_idx.size,
            )

            kl = self._generalized_kl(
                S_kl,
                U,
            )

            zeta_values.append(zeta)
            zeta_kl_values.append(float(kl))

            if (
                best is None
                or kl < best["kl"]
            ):
                best = {
                    "zeta": zeta,
                    "G": G,
                    "U": U,
                    "kl": float(kl),
                }

        if best is None:
            raise RuntimeError(
                "Ross recovery failed for every ridge penalty."
            )

        # Transition fit diagnostics.
        transition_residual = (
            A @ best["G"] - B
        )
        transition_fit_rmse = float(
            np.sqrt(
                np.mean(
                    transition_residual ** 2
                )
            )
        )
        B_rms = float(
            np.sqrt(
                np.mean(
                    B ** 2
                )
            )
        )
        transition_fit_relative_rmse = float(
            transition_fit_rmse
            / max(B_rms, self.state_price_floor)
        )

        kl_residual = best["U"] - S_kl
        selected_kl_rmse = float(
            np.sqrt(
                np.mean(
                    kl_residual ** 2
                )
            )
        )
        S_kl_rms = float(
            np.sqrt(
                np.mean(
                    S_kl ** 2
                )
            )
        )
        selected_kl_relative_rmse = float(
            selected_kl_rmse
            / max(S_kl_rms, self.state_price_floor)
        )

        G = best["G"]
        zero_tolerance = max(
            self.state_price_floor,
            1e-14,
        )
        transition_zero_fraction = float(
            np.mean(G <= zero_tolerance)
        )
        transition_row_sums = G.sum(axis=1)
        transition_min_row_sum = float(
            np.min(transition_row_sums)
        )
        transition_max_row_sum = float(
            np.max(transition_row_sums)
        )

        (
            physical_transition,
            lam,
            z,
            spectral,
        ) = self._ross_recover(G)

        kernel_recovery = (
            1.0 / np.maximum(z, self.eps)
        )
        kernel_recovery /= kernel_recovery[i0]

        warnings = []

        if A.shape[0] < A.shape[1]:
            warnings.append(
                "transition_system_underdetermined"
            )

        if transition_rank < min(A.shape):
            warnings.append(
                "transition_design_rank_deficient"
            )

        if (
            not np.isfinite(condition_number)
            or condition_number > 1e12
        ):
            warnings.append(
                "transition_design_extremely_ill_conditioned"
            )
        elif condition_number > 1e8:
            warnings.append(
                "transition_design_ill_conditioned"
            )

        if transition_fit_relative_rmse > 0.25:
            warnings.append(
                "transition_fit_relative_rmse_large"
            )

        if selected_kl_relative_rmse > 0.25:
            warnings.append(
                "unrolled_state_price_fit_relative_rmse_large"
            )

        if transition_zero_fraction > 0.90:
            warnings.append(
                "transition_matrix_extremely_sparse"
            )
        elif transition_zero_fraction > 0.75:
            warnings.append(
                "transition_matrix_sparse"
            )

        if not (0.0 < lam < 1.0):
            warnings.append(
                "dominant_eigenvalue_outside_discount_factor_range"
            )

        if (
            np.isfinite(spectral["subdominant_ratio"])
            and spectral["subdominant_ratio"] > 0.95
        ):
            warnings.append(
                "small_spectral_gap_recovery_sensitive"
            )

        if (
            np.isfinite(spectral["eigenpair_residual"])
            and spectral["eigenpair_residual"]
            > self.eigenpair_residual_tolerance
        ):
            warnings.append(
                "poor_dominant_eigenpair_residual"
            )

        if (
            source_idx.size < x.size
        ):
            warnings.append(
                "fewer_maturity_pairs_than_recovery_states"
            )

        if self.verbose:
            warning_text = (
                ",".join(warnings)
                if warnings
                else "none"
            )
            print(
                "[ross] "
                f"original_states={int(original_grid_size)} | "
                f"recovery_states={x.size} | "
                f"maturities={T_grid.size} | "
                f"transition_step={self.transition_step_days}d | "
                f"pairs={source_idx.size} | "
                f"A_shape={A.shape} | "
                f"rank={transition_rank} | "
                f"cond={condition_number:.3e} | "
                f"zeta={best['zeta']:.6g} | "
                f"KL={best['kl']:.6g} | "
                f"transition_rel_rmse="
                f"{transition_fit_relative_rmse:.3e} | "
                f"unrolled_rel_rmse="
                f"{selected_kl_relative_rmse:.3e} | "
                f"lambda={lam:.6g} | "
                f"sub/dom="
                f"{spectral['subdominant_ratio']:.6g} | "
                f"warnings={warning_text}"
            )

        return RossRecoveryOutput(
            state_price_matrix=S,
            state_price_transition=G,
            physical_transition=physical_transition,
            eigenvalue=float(lam),
            eigenfunction=z,
            pricing_kernel_recovery_grid=kernel_recovery,
            ridge_zeta=float(best["zeta"]),
            kl_loss=float(best["kl"]),
            current_state_index=int(i0),
            transition_step_days=int(
                self.transition_step_days
            ),
            transition_step_years=float(
                self.transition_step_days / 365.0
            ),
            transition_pair_count=int(
                source_idx.size
            ),
            transition_source_indices=source_idx,
            transition_target_indices=target_idx,
            kl_maturity_indices=kl_idx,
            dominant_eigenvalue=float(lam),
            subdominant_eigenvalue_abs=float(
                spectral["subdominant_abs"]
            ),
            subdominant_to_dominant_ratio=float(
                spectral["subdominant_ratio"]
            ),
            eigenpair_residual=float(
                spectral["eigenpair_residual"]
            ),
            recovered_transition_row_sum_error=float(
                spectral["row_sum_error"]
            ),
            transition_system_rows=int(A.shape[0]),
            transition_system_columns=int(A.shape[1]),
            transition_system_rank=int(
                transition_rank
            ),
            transition_system_condition_number=float(
                condition_number
            ),
            transition_fit_rmse=float(
                transition_fit_rmse
            ),
            transition_fit_relative_rmse=float(
                transition_fit_relative_rmse
            ),
            transition_matrix_zero_fraction=float(
                transition_zero_fraction
            ),
            transition_matrix_min_row_sum=float(
                transition_min_row_sum
            ),
            transition_matrix_max_row_sum=float(
                transition_max_row_sum
            ),
            selected_kl_reconstruction_rmse=float(
                selected_kl_rmse
            ),
            selected_kl_reconstruction_relative_rmse=float(
                selected_kl_relative_rmse
            ),
            zeta_values_tested=np.asarray(
                zeta_values,
                dtype=float,
            ),
            zeta_kl_values=np.asarray(
                zeta_kl_values,
                dtype=float,
            ),
            diagnostic_warnings=tuple(warnings),
            recovery_grid=x.copy(),
            recovery_grid_size=int(x.size),
            original_grid_size=int(
                original_grid_size
            ),
            recovery_grid_bounds=(
                float(x[0]),
                float(x[-1]),
            ),
        )

    def _solve_transition_nnls(
        self,
        A,
        B,
        zeta,
    ) -> np.ndarray:
        A = np.asarray(A, dtype=float)
        B = np.asarray(B, dtype=float)

        if A.ndim != 2 or B.ndim != 2:
            raise ValueError(
                "A and B must both be two-dimensional."
            )
        if A.shape != B.shape:
            raise ValueError(
                "A and B must have the same shape."
            )

        n_states = A.shape[1]
        G = np.zeros(
            (n_states, n_states),
            dtype=float,
        )

        if zeta > 0:
            A_aug = np.vstack([
                A,
                np.sqrt(zeta)
                * np.eye(n_states),
            ])
        else:
            A_aug = A

        for j in range(n_states):
            b = B[:, j]

            if zeta > 0:
                b_aug = np.r_[
                    b,
                    np.zeros(n_states),
                ]
            else:
                b_aug = b

            result = lsq_linear(
                A_aug,
                b_aug,
                bounds=(0.0, np.inf),
                method="trf",
                lsmr_tol="auto",
                max_iter=self.nnls_max_iter,
            )

            if (
                not result.success
                and self.verbose
            ):
                print(
                    "[ross warning] "
                    f"NNLS column {j} did not converge: "
                    f"{result.message}"
                )

            if np.any(~np.isfinite(result.x)):
                raise ValueError(
                    f"NNLS returned nonfinite values in column {j}."
                )

            G[:, j] = np.maximum(
                result.x,
                0.0,
            )

        # Do not add a positive floor to the transition matrix. The paper's
        # small constant is used in the KL calculation, not to alter P.
        return G

    def _markov_state_prices(
        self,
        G,
        *,
        i0,
        n_steps,
    ) -> np.ndarray:
        G = np.asarray(G, dtype=float)
        n_states = G.shape[0]

        U = np.zeros(
            (n_states, int(n_steps)),
            dtype=float,
        )

        row = np.zeros(
            n_states,
            dtype=float,
        )
        row[int(i0)] = 1.0

        for k in range(int(n_steps)):
            row = row @ G
            U[:, k] = row

        return np.maximum(
            U,
            self.state_price_floor,
        )

    def _generalized_kl(
        self,
        S,
        U,
    ) -> float:
        S = np.maximum(
            np.asarray(S, dtype=float),
            self.state_price_floor,
        )
        U = np.maximum(
            np.asarray(U, dtype=float),
            self.state_price_floor,
        )

        if S.shape != U.shape:
            raise ValueError(
                "S and U must have the same shape "
                "for generalized KL evaluation."
            )

        value = np.sum(
            S * np.log(S / U)
            - (S - U)
        )

        return (
            float(value)
            if np.isfinite(value)
            else np.inf
        )

    def _ross_recover(
        self,
        G,
    ):
        G = np.asarray(G, dtype=float)

        values, vectors = eig(G)

        finite = (
            np.isfinite(np.real(values))
            & np.isfinite(np.imag(values))
        )
        if not np.any(finite):
            raise ValueError(
                "The transition matrix has no finite eigenvalues."
            )

        candidates = np.where(finite)[0]
        idx = int(
            candidates[
                np.argmax(
                    np.real(values[candidates])
                )
            ]
        )

        lam_complex = values[idx]
        if abs(float(np.imag(lam_complex))) > 1e-8:
            raise ValueError(
                "The dominant eigenvalue is materially complex."
            )

        lam = float(np.real(lam_complex))
        if not np.isfinite(lam) or lam <= self.eps:
            raise ValueError(
                "Ross recovery requires a positive "
                "dominant eigenvalue."
            )

        z_complex = vectors[:, idx]
        if np.max(np.abs(np.imag(z_complex))) > 1e-8:
            raise ValueError(
                "The dominant right eigenvector is materially complex."
            )

        z = np.real(z_complex)

        if float(np.sum(z)) < 0:
            z = -z

        scale = max(
            float(np.max(np.abs(z))),
            1.0,
        )
        negative_tol = (
            self.eigenvector_negative_tolerance
            * scale
        )

        if float(np.min(z)) < -negative_tol:
            raise ValueError(
                "The dominant right eigenvector is not positive. "
                "The estimated transition matrix does not satisfy "
                "the required Perron recovery condition."
            )

        z = np.maximum(
            z,
            self.eps,
        )
        z /= np.mean(z)

        eigenpair_residual = float(
            np.linalg.norm(
                G @ z - lam * z
            )
            / max(
                np.linalg.norm(z),
                self.eps,
            )
        )

        # A poor eigenpair residual is diagnostic, not fatal. It is
        # recorded as a warning by _estimate_recovery_from_surface(), while
        # the recovered forecast remains available to the backtest.

        physical_transition = (
            G
            * (
                z[None, :]
                / np.maximum(
                    lam * z[:, None],
                    self.eps,
                )
            )
        )
        physical_transition = np.where(
            np.isfinite(physical_transition)
            & (physical_transition >= 0),
            physical_transition,
            0.0,
        )

        row_sums = physical_transition.sum(
            axis=1,
        )
        if (
            np.any(~np.isfinite(row_sums))
            or np.any(row_sums <= self.eps)
        ):
            raise ValueError(
                "Recovered physical transition matrix "
                "has invalid row sums."
            )

        row_sum_error = float(
            np.max(
                np.abs(row_sums - 1.0)
            )
        )

        # Small numerical normalization only.
        physical_transition = (
            physical_transition
            / row_sums[:, None]
        )

        abs_values = np.sort(
            np.abs(values[finite])
        )[::-1]

        subdominant_abs = (
            float(abs_values[1])
            if abs_values.size > 1
            else np.nan
        )
        subdominant_ratio = (
            float(subdominant_abs / abs(lam))
            if (
                np.isfinite(subdominant_abs)
                and abs(lam) > self.eps
            )
            else np.nan
        )

        spectral = {
            "subdominant_abs":
                subdominant_abs,
            "subdominant_ratio":
                subdominant_ratio,
            "eigenpair_residual":
                eigenpair_residual,
            "row_sum_error":
                row_sum_error,
        }

        return (
            physical_transition,
            lam,
            z,
            spectral,
        )

    def _physical_surface_from_eigenfunction(
        self,
        *,
        x_grid,
        state_price_matrix,
        z,
    ) -> np.ndarray:
        x = _as_1d(x_grid)
        z = _as_1d(z)
        S = np.asarray(
            state_price_matrix,
            dtype=float,
        )

        if S.shape[0] != x.size:
            raise ValueError(
                "state_price_matrix must have one row per state."
            )
        if z.size != x.size:
            raise ValueError(
                "z must have one value per state."
            )

        dx = np.gradient(x)
        rows = []

        for j in range(S.shape[1]):
            recovered_mass = (
                z
                * np.maximum(
                    S[:, j],
                    0.0,
                )
            )

            total = float(
                np.sum(recovered_mass)
            )
            if (
                not np.isfinite(total)
                or total <= self.eps
            ):
                raise ValueError(
                    "Recovered physical probability mass is invalid "
                    f"at maturity index {j}."
                )

            recovered_mass = (
                recovered_mass / total
            )

            density = (
                recovered_mass
                / np.maximum(dx, self.eps)
            )
            density = _trapz_normalize_density(
                x,
                density,
                eps=self.eps,
            )

            if np.any(~np.isfinite(density)):
                raise ValueError(
                    "Recovered physical density is invalid "
                    f"at maturity index {j}."
                )

            rows.append(density)

        return np.vstack(rows)
